/** Keep the new catalog and Home in sync with the demo checkout's local stock. */
export function useListingBooks(): Book[] {
  const stock = useStock();
  return BOOKS.map((sample) => {
    const book = getBookByIsbn(sample.isbn);
    return book ? {
      ...sample,
      isbn: book.isbn,
      title: book.title,
      author: book.author,
      price: lowestAvailablePrice(stock.get(book.isbn) ?? []),
    } : sample;
  });
}
